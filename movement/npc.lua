local h=require("helpers")
local walk,turn=h.walk,h.turn
return function(p)
    local name,slot=p.name,p.slot
    local path={walk({{5,"forward"},{9.2 * slot - 4,"right"}})}
    if name == "Black Bear" then
        path[#path+1]=walk({{10,"backward"},{13.5,"right"},{6,"forward"},{6,"backward"}})
    elseif name == "Brown Bear" then
        path[#path+1]=walk({{44.75,"backward","left"},{42.5,"left"},{8.5,"backward"},{22.5,"left"}})
        path[#path+1]=turn("rotate_left")
        path[#path+1]=walk({{40,"forward"},{1.2,"backward"},{15,"right"}})
    elseif name == "Polar Bear" then
        path[#path+1]=walk({{67.5,"backward","left"}})
        path[#path+1]=turn("rotate_right",4)
        path[#path+1]=walk({{31.5,"forward"},{9,"left"},{9,"backward"},{58.5,"left"},{49.5,"forward"},{3.375,"left"}})
        path[#path+1]=walk({{36,"forward"},{60,"right"},{60,"backward"},{9,"left"},{9,"forward"},{5,"backward"},{2,"right"}})
    elseif name == "Honey Bee" then
        path[#path+1]=walk({{67.5,"backward","left"}})
        path[#path+1]=turn("rotate_right",4)
        path[#path+1]=walk({{31.5,"forward"},{9,"left"},{9,"backward"},{58.5,"left"},{49.5,"forward"},{2.25,"backward","left"},{36,"left"}})
        path[#path+1]=turn("rotate_left",2)
        local climb=h.motion()
        climb:hold({"forward","jump"},300)
        climb:hold({"forward"},500)
        for i=1,2 do
            climb:hold({"forward","rotate_right"},50)
            climb:hold({"forward"},50)
        end
        climb:hold({"forward"},1000)
        climb:hold({"forward","jump"},300)
        climb:walk(6,{"forward"})
        climb:walk(6,{"right"})
        climb:walk(7,{"forward"})
        climb:walk(6,{"left"})
        climb:walk(3,{"right"})
        climb:walk(32,{"forward"})
        climb:walk(8.5,{"backward"})
        path[#path+1]=climb:finish()
    elseif name == "Bucko Bee" then
        path[#path+1]=walk({{88.875,"backward","left"},{27,"left"}})
        path[#path+1]=turn("rotate_left")
        path[#path+1]=walk({{50,"forward"}})
        local door=h.motion()
        door:hold({"jump"},100)
        door:walk(6,{"forward"})
        door:walk(5,{"right"})
        door:walk(9,{"right","backward"})
        door:walk(4,{"right"})
        door:walk(2,{"left"})
        door:walk(28,{"backward"})
        door:walk(1.75,{"forward"})
        door:walk(9.5,{"left"})
        door:walk(6.5,{"forward"})
        door:hold({},100)
        door:hold({"jump"},300)
        door:walk(5,{"forward"})
        path[#path+1]=door:finish()
    elseif name == "Riley Bee" then
        local ledge=h.motion()
        ledge:hold({"jump"},100)
        ledge:walk(2,{"right"})
        ledge:walk(1.8,{"forward","right"})
        ledge:walk(32,{"right"})
        ledge:hold({"jump"},300)
        ledge:walk(2,{"right"})
        ledge:walk(6,{"right","forward"})
        ledge:walk(3,{"right"})
        path[#path+1]=ledge:finish()
        path[#path+1]=turn("rotate_right")
        local hop=h.motion()
        hop:hold({"forward","jump"},300)
        hop:walk(2,{"forward"})
        hop:hold({},1000)
        hop:hold({"right","jump"},100)
        hop:hold({"right"},100)
        hop:hold({"right","jump"},100)
        hop:hold({"right"},100)
        hop:hold({"jump"},100)
        hop:hold({},1000)
        hop:walk(1,{"forward","right"})
        hop:walk(20,{"right"})
        hop:walk(2,{"forward"})
        hop:walk(12,{"forward","right"})
        hop:walk(10,{"forward"})
        hop:walk(6,{"backward"})
        path[#path+1]=hop:finish()
        path[#path+1]=turn("rotate_right")
        local finish=h.motion()
        finish:walk(5,{"forward"})
        finish:hold({},100)
        finish:hold({"jump"},300)
        finish:walk(6,{"forward"})
        finish:hold({},300)
        path[#path+1]=finish:finish()
    end
    return path
end
