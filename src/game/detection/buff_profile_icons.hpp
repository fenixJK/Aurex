// Native lower-icon profiles retain their original sample widths. The shared
// matcher requires color detail as well as similarity for these small references.
struct BuffProfile { BuffIcon icon; double width; };
template<std::size_t N>
constexpr BuffProfile profile(std::string_view name,const std::array<std::uint32_t,N>& pixels) {
    BuffIcon icon{name,{},6,unsigned(N),1};
    std::copy(pixels.begin(),pixels.end(),icon.pixels.begin());
    return {icon,double(N)};
}
