"""Generate compact native HUD caption references (requires Pillow).

Pass Roblox's HWYGOTH.ttf as the font argument. The font is only needed to
regenerate the references; the application never loads or renders it.
"""

import argparse
import hashlib
import math
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont


def reference(font_path, value, raster_size):
    text = f"x{value}"
    for size in range(raster_size, 0, -1):
        font = ImageFont.truetype(str(font_path), size)
        left, top, right, bottom = font.getbbox(text)
        width, height = right - left + 2, bottom - top + 2
        if width <= 32 and height <= 18:
            break
    else:
        raise ValueError(f"Caption {text} does not fit the reference format")

    image = Image.new("L", (width, height))
    ImageDraw.Draw(image).text((1 - left, 1 - top), text, font=font, fill=255)
    rows = [
        sum(((image.getpixel((x, y)) + 42) // 85) << (2 * x) for x in range(width))
        for y in range(height)
    ]
    # Measure the multiplier's advance with the actual following digits, so
    # kerning and text fitted into a narrower cell retain their own geometry.
    advance = font.getlength(text) - font.getlength(str(value))
    number_offset = max(1, math.floor(1 - left + advance))
    if number_offset >= width:
        raise ValueError(f"Caption {text} has no numeric region")
    packed = ",".join(f"{row:#x}ULL" for row in rows)
    return f"    {{{value},{width},{height},{{{packed}}},{number_offset}}},"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("font", type=Path)
    parser.add_argument(
        "--output", type=Path,
        default=Path(__file__).resolve().parents[2] / "src/game/detection/native_buff_counters.hpp",
    )
    args = parser.parse_args()
    digest = hashlib.sha256(args.font.read_bytes()).hexdigest()
    lines = [
        "#pragma once", '#include "buff_counters.hpp"',
        "namespace hive::game::detail {",
        "// Generated by assets/buffs/generate_counter_references.py from HWYGOTH.ttf.",
        f"// Font SHA-256: {digest}",
        "// Raster variants and numeric starts are data for the shared caption matcher.",
    ]
    for raster_size in (18, 17):
        lines.append(f"inline constexpr std::array<BuffCounter,99> buff_native_counters_{raster_size}{{{{")
        lines.extend(reference(args.font, value, raster_size) for value in range(2, 101))
        lines.append("}};")
    lines.append("}")
    args.output.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
