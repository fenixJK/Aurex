"""Build single-stack artwork references from the shipped buff assets.

Run with Pillow, NumPy and OpenCV installed. This is an asset-generation tool;
the application uses only the generated header.
"""
from pathlib import Path

import cv2
import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
NAMES = (
    "Bomb Combo", "Inspire", "Haste", "Blue Boost", "Red Boost", "White Boost",
    "Balloon Aura", "Focus", "Precision", "Honey Mark", "Pollen Mark", "Rage",
    "Reindeer Fetch",
)


def reference(name):
    path = ROOT / "assets/buffs" / (name.lower().replace(" ", "-") + ".png")
    image = np.array(Image.open(path).convert("RGBA"))
    rgb = image[:, :, :3].astype(float)
    # Round source artwork has transparent corners and antialiased outer
    # edges. Sample the opaque perimeter, not the transparent RGB padding.
    height, width = image.shape[:2]
    y, x = np.mgrid[:height, :width]
    radius = ((x - (width - 1) / 2) / (width / 2)) ** 2 + ((y - (height - 1) / 2) / (height / 2)) ** 2
    perimeter = (radius > .72) & (image[:, :, 3] > 240)
    colors, counts = np.unique(rgb[perimeter], axis=0, return_counts=True)
    background = colors[counts.argmax()].astype(float)
    mask = (np.max(abs(rgb - background), axis=2) >= 28) * image[:, :, 3] / 255
    # Preserve the lower symbol, masking out its changing timer background.
    foreground = cv2.resize(rgb * mask[:, :, None], (38, 38), interpolation=cv2.INTER_AREA)[22:38, 3:35]
    coverage = cv2.resize(mask, (38, 38), interpolation=cv2.INTER_AREA)[22:38, 3:35]
    foreground = cv2.resize(foreground, (12, 8), interpolation=cv2.INTER_AREA)
    coverage = cv2.resize(coverage, (12, 8), interpolation=cv2.INTER_AREA)
    pixels = np.clip(np.rint(foreground / np.maximum(coverage[:, :, None], 1e-5)), 0, 255).astype(int)
    return pixels, np.rint(coverage * 255).astype(int), background


def generate():
    lines = [
        "#pragma once", '#include "buff_icon.hpp"', "namespace hive::game::detail {",
        "// Generated by assets/buffs/generate_uncaptioned_references.py.",
        "// Uncaptioned lower artwork at nominal region (3,22,32,16).",
        "// The coverage mask excludes the changing timer background.",
        f"inline constexpr std::array<BuffIcon,{len(NAMES)}> uncaptioned_buff_icons{{{{",
    ]
    for name in NAMES:
        pixels, coverage, background = reference(name)
        lines.append('    {"' + name + '",{{')
        for row in pixels:
            lines.append("        " + ",".join(f"0x{r:02x}{g:02x}{b:02x}" for r, g, b in row) + ",")
        lines.append("    }},18,12,8,{{")
        for row in coverage:
            lines.append("        " + ",".join(map(str, row)) + ",")
        lines.append("    }},0x" + "".join(f"{int(v):02x}" for v in background) + "},")
    lines += ["}};", "}"]
    (ROOT / "src/game/detection/uncaptioned_buff_icons.hpp").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    generate()
