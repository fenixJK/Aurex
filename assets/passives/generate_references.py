"""Build passive HUD artwork and numeral references; no screenshots at runtime.

The input icon is the square Star Saw artwork, including its circular border.
Font arguments are Roblox HWYGOTH.ttf and BuilderSans-Bold.otf.
"""
import argparse
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

p = argparse.ArgumentParser(description=__doc__)
p.add_argument('icon', type=Path)
p.add_argument('fonts', type=Path, nargs='+')
p.add_argument('--output', type=Path, default=Path('src/game/detection/passive_references.hpp'))
a = p.parse_args()
icon = Image.open(a.icon).convert('L').resize((32, 32), Image.Resampling.LANCZOS).crop((4, 12, 28, 25))
lines = ['#pragma once', '#include <array>', '#include <cstdint>', 'namespace hive::game::detail {',
         '// Generated by assets/passives/generate_references.py. Artwork excludes the charge counter and ring.',
         'inline constexpr std::array<std::uint8_t,312> saw_art{{' + ','.join(map(str,icon.getdata())) + '}};',
         'struct PassiveDigit { unsigned value; int width,height; std::array<std::uint8_t,600> pixels; };',
         'inline constexpr std::array<PassiveDigit,' + str(3 * len(a.fonts)) + '> passive_digits{{']
for path in a.fonts:
    font = ImageFont.truetype(str(path), 24)
    for n in range(3):
        bb = font.getbbox(str(n))
        im = Image.new('L', (bb[2]-bb[0]+4, bb[3]-bb[1]+4))
        ImageDraw.Draw(im).text((2-bb[0], 2-bb[1]), str(n), font=font, fill=255)
        lines.append('    {' + f'{n},{im.width},{im.height},' + '{' + ','.join(map(str,im.getdata())) + '}},')
lines += ['}};', '}']
a.output.write_text('\n'.join(lines) + '\n')
